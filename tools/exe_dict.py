KEEP_IDS = {'E0005', 'E0016', 'E0017', 'E0039'}          # 이름표 글리프(따로 그림)·글자 대응표·조각


def tr_of(src):
    if src in FULL:
        return FULL[src]
    if src.startswith('{01}') and src[4:] in SUF:
        return '{01}' + SUF[src[4:]]
    if src.endswith('{01}') and src[:-4] in PRE:
        return PRE[src[:-4]] + ' {01}'
    return None


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    miss = []; filled = 0
    for p in sorted(glob.glob(os.path.join(ROOT, 'my files', 'tsv', 'linda3_exe_*.tsv'))):
        raw = open(p, 'rb').read(); nl = '\r\n' if b'\r\n' in raw else '\n'
        rows = list(csv.reader(open(p, encoding='utf-8'), delimiter='\t', quoting=csv.QUOTE_NONE))
        for r in rows[1:]:
            if r[5].strip() or r[0] in KEEP_IDS:
                continue
            t = tr_of(r[4])
            if t is None:
                if not all(0x391 <= ord(c) <= 0x3A9 for c in r[4]) and r[4] not in ('ＧＥＮＤＥＲ　ＣＨＡＮＧＥ', 'ダミー', '{05}α', '{05}β'):
                    miss.append((r[0], r[4]))
                continue
            r[5] = t; filled += 1
        if '--write' in sys.argv:
            open(p, 'w', encoding='utf-8', newline='').write(''.join('\t'.join(x) + nl for x in rows))
    print('채움 %d · 사전에 없음 %d' % (filled, len(miss)))
    for m in miss:
        print(' ', *m)


if __name__ == '__main__':
    main()
